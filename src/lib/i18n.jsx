const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const saved = localStorage.getItem('tetrix_lang')
    if (saved && translations[saved]) return saved
    // Auto-detect from browser
    const browser = navigator.language?.split('-')[0]
    return translations[browser] ? browser : 'en'
  })

  function setLanguage(code) {
    if (!translations[code]) return
    localStorage.setItem('tetrix_lang', code)
    setLang(code)
    // Apply RTL for Arabic
    document.documentElement.dir = LANGUAGES.find(l => l.code === code)?.rtl ? 'rtl' : 'ltr'
    document.documentElement.lang = code
  }

  // Apply on mount
  useEffect(() => {
    const isRtl = LANGUAGES.find(l => l.code === lang)?.rtl
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr'
    document.documentElement.lang = lang
  }, [])

  function t(key) {
    return translations[lang]?.[key] ?? translations['en']?.[key] ?? key
  }

  return (
    <I18nContext.Provider value={{ lang, setLanguage, t, isRtl: LANGUAGES.find(l => l.code === lang)?.rtl }}>
      {children}
    </I18nContext.Provider>
  )
}

export const useI18n = () => useContext(I18nContext)
